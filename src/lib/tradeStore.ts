"use client";

// Trade persistence store.
//
// On mount we try to load the trade history from the server-side
// /api/trades endpoint (which uses the service-role Supabase client and the
// HttpOnly session cookie to set user_id). If the session is not
// authenticated (paper mode) or the request fails, we fall back to an
// in-memory list.
//
// The store also exposes the same `addTrade` / `closeTrade` actions the
// TradePanel and bot use to record new positions. These now flow through
// server-side endpoints so that:
//   - user_id is set from the server session (never trusted from the client)
//   - clientOrderId is checked for idempotency (no duplicate orders)
//   - Supabase insert failures are surfaced to the user with a toast and
//     the trade is marked `persisted: false` in local state for retry via
//     `syncPendingTrades()`.

import { create } from "zustand";
import { toast } from "sonner";
import { supabase } from "@/lib/supabase";
import type { TradeRow } from "@/lib/supabase";
import { useAuthStore } from "@/lib/authStore";

// ---- Shared trade types -----------------------------------------------------

export type TradeStatus = "open" | "closed";
export type TradeSide = "buy" | "sell";
export type TradeResult = "win" | "loss" | null;
export type TradeSource = "seed" | "agent" | "bot" | "manual" | "paper";

export interface Trade {
  id: string;
  status: TradeStatus;
  datetime: number; // ms timestamp
  market: string;
  side: TradeSide;
  amount: number; // $ notional
  entryPrice: number;
  exitPrice: number | null;
  pnl: number;
  pnlPct: number;
  result: TradeResult;
  agentId: string | null;
  source: TradeSource;
  /** Idempotency key (UUID) generated by the client for broker trades. */
  clientOrderId?: string | null;
  /** Broker order id (null for paper trades). */
  brokerOrderId?: string | null;
  /**
   * Broker-reported position open time (ms). Captured from MetaApi's
   * response.openTime / position.time when the order is placed.
   */
  brokerOpenTime?: number | null;
  /** Broker-reported position close time (ms). */
  brokerCloseTime?: number | null;
  /** Hold time (ms), derived from the broker timestamps. */
  holdTimeMs?: number | null;
  /** True when the trade has been confirmed persisted to Supabase. */
  persisted?: boolean;
}

// ---- Helpers ---------------------------------------------------------------

let liveCounter = 0;
function liveId(prefix: string): string {
  liveCounter += 1;
  return `${prefix}-${Date.now().toString(36)}-${liveCounter}`;
}

function rowToTrade(row: TradeRow): Trade {
  const brokerOpenTime = row.broker_open_time
    ? new Date(row.broker_open_time).getTime()
    : null;
  const brokerCloseTime = row.broker_close_time
    ? new Date(row.broker_close_time).getTime()
    : null;
  const holdTimeMs =
    typeof row.hold_time_ms === "number" && row.hold_time_ms > 0
      ? row.hold_time_ms
      : brokerOpenTime != null && brokerCloseTime != null && brokerCloseTime > brokerOpenTime
        ? brokerCloseTime - brokerOpenTime
        : null;
  return {
    id: row.id,
    status: row.status,
    datetime: new Date(row.datetime).getTime(),
    market: row.market,
    side: row.side,
    amount: Number(row.amount),
    entryPrice: Number(row.entry_price),
    exitPrice: row.exit_price != null ? Number(row.exit_price) : null,
    pnl: Number(row.pnl),
    pnlPct: Number(row.pnl_pct),
    result: row.result,
    agentId: row.agent_id,
    source: row.source,
    clientOrderId: row.client_order_id ?? null,
    brokerOrderId: row.broker_order_id ?? null,
    brokerOpenTime,
    brokerCloseTime,
    holdTimeMs,
    persisted: true,
  };
}

function isSupabaseConfigured(): boolean {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) return false;
  if (url.includes("placeholder.supabase.co")) return false;
  if (key.includes("placeholder-anon-key")) return false;
  return true;
}

function hasServerSession(): boolean {
  const state = useAuthStore.getState();
  // Paper mode intentionally has no server session — trades stay local.
  return state.isAuthenticated && state.tradingMode !== "paper" && !!state.userId;
}

// ---- Store -----------------------------------------------------------------

interface TradeStoreState {
  trades: Trade[];
  loading: boolean;
  usingSupabase: boolean;
  loaded: boolean;

  fetchTrades: () => Promise<void>;
  addTrade: (trade: Trade) => Promise<void>;
  closeTrade: (
    id: string,
    exitPrice: number,
    pnl: number,
    pnlPct: number,
    result: "win" | "loss",
  ) => Promise<void>;

  /**
   * Retry persisting trades that previously failed to save to Supabase
   * (marked `persisted: false`). Called on mount and after balance refreshes.
   */
  syncPendingTrades: () => Promise<void>;

  // Local-only variants (no Supabase round-trip — used by the bot's tight
  // automation loop to avoid latency).
  addTradeLocal: (trade: Trade) => void;
  closeTradeLocal: (
    id: string,
    exitPrice: number,
    pnl: number,
    pnlPct: number,
    result: "win" | "loss",
  ) => void;
}

export const useTradeStore = create<TradeStoreState>((set, get) => ({
  trades: [],
  loading: false,
  usingSupabase: isSupabaseConfigured(),
  loaded: false,

  fetchTrades: async () => {
    if (get().loaded) return;
    set({ loading: true });
    if (!get().usingSupabase || !hasServerSession()) {
      set({ loading: false, loaded: true });
      return;
    }
    try {
      const res = await fetch("/api/trades", { cache: "no-store" });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const data = (await res.json()) as { trades?: TradeRow[] };
      const trades = (data.trades ?? []).map(rowToTrade);
      set({ trades, loading: false, loaded: true });
    } catch (err) {
      console.warn("[tradeStore] fetchTrades failed, falling back to local:", err);
      set({ loading: false, loaded: true });
    }
  },

  addTrade: async (trade) => {
    // Always update local state immediately so the UI is responsive.
    set((s) => ({ trades: [trade, ...s.trades].slice(0, 1000) }));

    if (!get().usingSupabase) return;

    // Paper mode or no server session: write via the browser supabase client
    // as a best-effort (RLS will allow it only if the deploy disabled RLS;
    // otherwise the insert silently fails and the trade stays local).
    if (!hasServerSession()) {
      try {
        const row = tradeToRow(trade, null);
        const { error } = await supabase.from("trades").insert(row);
        if (error) {
          console.warn("[tradeStore] local insert failed:", error.message);
          markUnpersisted(set, trade.id);
        }
      } catch (err) {
        console.warn("[tradeStore] local insert threw:", err);
        markUnpersisted(set, trade.id);
      }
      return;
    }

    // Authenticated session: write via the server-side /api/trades endpoint
    // so user_id is set from the session and clientOrderId is checked for
    // idempotency.
    try {
      const res = await fetch("/api/trades", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(tradeToRequestBody(trade)),
        cache: "no-store",
      });
      if (!res.ok) {
        const err = (await res.json().catch(() => ({}))) as { error?: string };
        throw new Error(err.error ?? `HTTP ${res.status}`);
      }
      const data = (await res.json()) as {
        ok?: boolean;
        persisted?: boolean;
        idempotent?: boolean;
        trade?: TradeRow;
      };
      if (data.persisted === false) {
        markUnpersisted(set, trade.id);
        toast.error("Failed to save trade to database", {
          description: "The trade was recorded locally and will retry on sync.",
        });
      }
    } catch (err) {
      console.warn("[tradeStore] addTrade server insert failed:", err);
      markUnpersisted(set, trade.id);
      toast.error("Failed to save trade to database", {
        description: err instanceof Error ? err.message : String(err),
      });
    }
  },

  closeTrade: async (id, exitPrice, pnl, pnlPct, result) => {
    set((s) => ({
      trades: s.trades.map((t) =>
        t.id === id
          ? {
              ...t,
              status: "closed",
              exitPrice,
              pnl,
              pnlPct,
              result,
              // If the caller didn't supply a broker close time, fall back to
              // "now" for trades that have a broker open time (best-effort
              // hold-time estimate until the broker reports the real value).
              brokerCloseTime:
                t.brokerCloseTime ?? (t.brokerOpenTime != null ? Date.now() : null),
              holdTimeMs:
                t.holdTimeMs ??
                (t.brokerOpenTime != null
                  ? (t.brokerCloseTime ?? Date.now()) - t.brokerOpenTime
                  : null),
            }
          : t,
      ),
    }));
    if (!get().usingSupabase) return;

    // Paper mode: update via browser client (best-effort).
    if (!hasServerSession()) {
      try {
        const trade = get().trades.find((tt) => tt.id === id);
        const { error } = await supabase
          .from("trades")
          .update({
            status: "closed",
            exit_price: exitPrice,
            pnl,
            pnl_pct: pnlPct,
            result,
            broker_close_time: trade?.brokerCloseTime != null
              ? new Date(trade.brokerCloseTime).toISOString()
              : null,
            hold_time_ms: trade?.holdTimeMs ?? null,
          })
          .eq("id", id);
        if (error) {
          console.warn("[tradeStore] local close failed:", error.message);
        }
      } catch (err) {
        console.warn("[tradeStore] local close threw:", err);
      }
      return;
    }

    try {
      const trade = get().trades.find((tt) => tt.id === id);
      const res = await fetch(`/api/trades/${encodeURIComponent(id)}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          status: "closed",
          exitPrice,
          pnl,
          pnlPct,
          result,
          brokerCloseTime: trade?.brokerCloseTime != null
            ? new Date(trade.brokerCloseTime).toISOString()
            : null,
          holdTimeMs: trade?.holdTimeMs ?? null,
        }),
        cache: "no-store",
      });
      if (!res.ok) {
        const err = (await res.json().catch(() => ({}))) as { error?: string };
        console.warn("[tradeStore] closeTrade server update failed:", err.error);
      }
    } catch (err) {
      console.warn("[tradeStore] closeTrade server update threw:", err);
    }
  },

  syncPendingTrades: async () => {
    if (!get().usingSupabase || !hasServerSession()) return;
    const pending = get().trades.filter((t) => t.persisted === false);
    if (pending.length === 0) return;
    for (const trade of pending) {
      try {
        const res = await fetch("/api/trades", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(tradeToRequestBody(trade)),
          cache: "no-store",
        });
        if (res.ok) {
          const data = (await res.json()) as { persisted?: boolean };
          if (data.persisted !== false) {
            set((s) => ({
              trades: s.trades.map((t) =>
                t.id === trade.id ? { ...t, persisted: true } : t,
              ),
            }));
          }
        }
      } catch (err) {
        console.warn("[tradeStore] syncPendingTrades retry failed:", err);
      }
    }
  },

  addTradeLocal: (trade) =>
    set((s) => ({ trades: [trade, ...s.trades].slice(0, 1000) })),

  closeTradeLocal: (id, exitPrice, pnl, pnlPct, result) =>
    set((s) => ({
      trades: s.trades.map((t) =>
        t.id === id
          ? {
              ...t,
              status: "closed",
              exitPrice,
              pnl,
              pnlPct,
              result,
            }
          : t,
      ),
    })),
}));

function markUnpersisted(
  set: (fn: (s: TradeStoreState) => Partial<TradeStoreState>) => void,
  id: string,
) {
  set((s) => ({
    trades: s.trades.map((t) =>
      t.id === id ? { ...t, persisted: false } : t,
    ),
  }));
}

function tradeToRow(t: Trade, userId: string | null): Omit<TradeRow, "created_at"> {
  return {
    id: t.id,
    status: t.status,
    datetime: new Date(t.datetime).toISOString(),
    market: t.market,
    side: t.side,
    amount: t.amount,
    entry_price: t.entryPrice,
    exit_price: t.exitPrice,
    pnl: t.pnl,
    pnl_pct: t.pnlPct,
    result: t.result,
    agent_id: t.agentId,
    source: t.source,
    user_id: userId,
    broker_open_time: t.brokerOpenTime != null ? new Date(t.brokerOpenTime).toISOString() : null,
    broker_close_time: t.brokerCloseTime != null ? new Date(t.brokerCloseTime).toISOString() : null,
    hold_time_ms: t.holdTimeMs ?? null,
  };
}

function tradeToRequestBody(t: Trade): Record<string, unknown> {
  return {
    id: t.id,
    clientOrderId: t.clientOrderId ?? undefined,
    status: t.status,
    datetime: new Date(t.datetime).toISOString(),
    market: t.market,
    side: t.side,
    amount: t.amount,
    entryPrice: t.entryPrice,
    exitPrice: t.exitPrice,
    pnl: t.pnl,
    pnlPct: t.pnlPct,
    result: t.result,
    agentId: t.agentId,
    source: t.source,
    brokerOrderId: t.brokerOrderId ?? null,
    brokerOpenTime: t.brokerOpenTime != null ? new Date(t.brokerOpenTime).toISOString() : null,
    brokerCloseTime: t.brokerCloseTime != null ? new Date(t.brokerCloseTime).toISOString() : null,
    holdTimeMs: t.holdTimeMs ?? null,
  };
}

// ---- Hook ------------------------------------------------------------------

export function useTrades(): Trade[] {
  return useTradeStore((s) => s.trades);
}

export function newTradeId(prefix: TradeSource): string {
  return liveId(prefix);
}

/**
 * Generate a UUID-style clientOrderId for idempotent broker submissions.
 * Uses crypto.randomUUID when available, falls back to a time-based id.
 */
export function newClientOrderId(): string {
  try {
    if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
      return crypto.randomUUID();
    }
  } catch {
    /* fall through */
  }
  return `co-${Date.now().toString(36)}-${Math.floor(Math.random() * 1e9).toString(36)}`;
}

// ---- Stats helper (used by Dashboard / Agents views) -----------------------

export interface AgentTradeStats {
  winRate: number;
  totalTrades: number;
  pnl: number;
  sparkline: number[];
}

export function computeAgentStats(
  trades: Trade[],
  agentId: string,
): AgentTradeStats {
  const closed = trades.filter(
    (t) => t.agentId === agentId && t.status === "closed",
  );
  const wins = closed.filter((t) => t.result === "win").length;
  const pnl = closed.reduce((sum, t) => sum + t.pnl, 0);
  const totalTrades = closed.length;
  const winRate =
    totalTrades > 0 ? Math.round((wins / totalTrades) * 1000) / 10 : 0;
  const sparkline = closed
    .slice(-20)
    .reduce<number[]>((acc, t) => {
      const prev = acc.length > 0 ? acc[acc.length - 1] : 0;
      acc.push(Math.round((prev + t.pnl) * 100) / 100);
      return acc;
    }, []);
  return {
    winRate,
    totalTrades,
    pnl: Math.round(pnl * 100) / 100,
    sparkline,
  };
}
